-- Enables partial payment of payables: each payment made against a payable
-- is recorded as its own row here (mirrors delivery_payment for deliveries)
-- instead of a payable only ever transitioning unpaid -> fully paid in one
-- shot. amount_paid is derived client-side by summing this table;
-- payable.paid_date is still set, but only once the running total reaches
-- the payable's amount.
--
-- Purely additive: one new table. Nothing existing is touched.
-- Safe to re-run: every statement is guarded.

CREATE TABLE IF NOT EXISTS payable_payment (
  id bigint generated by default as identity primary key,
  payable_id bigint NOT NULL REFERENCES payable(id) ON DELETE CASCADE,
  payment_mode_id bigint REFERENCES payment_mode(id),
  amount numeric NOT NULL,
  source_date date,
  source_type bigint REFERENCES item_type(id),
  remarks text,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE payable_payment ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "payable_payment_select_own" ON payable_payment;
CREATE POLICY "payable_payment_select_own" ON payable_payment
  FOR SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "payable_payment_insert_own" ON payable_payment;
CREATE POLICY "payable_payment_insert_own" ON payable_payment
  FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "payable_payment_delete_own" ON payable_payment;
CREATE POLICY "payable_payment_delete_own" ON payable_payment
  FOR DELETE USING (auth.uid() = user_id);
