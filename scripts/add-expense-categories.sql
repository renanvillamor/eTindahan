-- Adds expense categorization (with an "operating expense" flag) and an
-- optional coverage period for periodic opex (rent, salaries, etc.) so it
-- can be amortized across the days it covers in profitability reporting.
--
-- Purely additive: a new table, plus new NULLABLE columns on `expense`.
-- Nothing existing is renamed or retyped — the old `source_type`
-- (item_type) column is left untouched and still readable. Step 5 below
-- DOES backfill old expense rows' category (source_type -> a matching new
-- expense_category, created if it doesn't exist yet) so historical rows
-- get properly categorized under the new system too, not just left
-- read-only under the old one.
--
-- Safe to re-run: every statement is guarded (IF NOT EXISTS / ON CONFLICT
-- / "only touch rows not already migrated").

-- 1. Expense category lookup table — same shape as `payment_mode` / `uom`.
CREATE TABLE IF NOT EXISTS expense_category (
  id bigint generated by default as identity primary key,
  name text NOT NULL,
  is_opex boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Standard per-user ownership policy — same shape as the other user_id-
-- scoped reference tables. Without this, the table is created with RLS off
-- (readable/writable by anyone with API access) unless the project forces
-- RLS on new tables by default, in which case it'd be the opposite: totally
-- inaccessible (empty result, no error) until a policy like this exists.
-- Guarded with DROP POLICY IF EXISTS so this block is safe to re-run.
ALTER TABLE expense_category ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "expense_category_select_own" ON expense_category;
CREATE POLICY "expense_category_select_own" ON expense_category
  FOR SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "expense_category_insert_own" ON expense_category;
CREATE POLICY "expense_category_insert_own" ON expense_category
  FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "expense_category_update_own" ON expense_category;
CREATE POLICY "expense_category_update_own" ON expense_category
  FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "expense_category_delete_own" ON expense_category;
CREATE POLICY "expense_category_delete_own" ON expense_category
  FOR DELETE USING (auth.uid() = user_id);

-- 2. Link expenses to a category (nullable — old rows simply won't have one).
ALTER TABLE expense
  ADD COLUMN IF NOT EXISTS expense_category_id bigint REFERENCES expense_category(id);

-- 3. Optional coverage period for periodic/amortized opex. Both null means
--    "cash-basis" (counts fully on source_date, same behavior as today).
ALTER TABLE expense
  ADD COLUMN IF NOT EXISTS coverage_start_date date;
ALTER TABLE expense
  ADD COLUMN IF NOT EXISTS coverage_end_date date;

-- 4. Seed a starting set of categories for the user.
DO $$
DECLARE
  v_user_id uuid := '8a00891a-6617-4806-99b3-3dcc2fbe44ed';
BEGIN
  INSERT INTO expense_category (name, is_opex, user_id)
  SELECT v.name, v.is_opex, v_user_id
  FROM (VALUES
    ('Rent', true),
    ('Utilities', true),
    ('Payroll', true),
    ('Supplies', false),
    ('Delivery Payment', false),
    ('Miscellaneous', false)
  ) AS v(name, is_opex)
  WHERE NOT EXISTS (
    SELECT 1 FROM expense_category ec
    WHERE ec.user_id = v_user_id AND lower(ec.name) = lower(v.name)
  );
END $$;

-- 5. Backfill old expense rows onto the new category system. For every
--    distinct item_type that was ever used as an expense's source_type,
--    find-or-create a matching expense_category (matched by name,
--    case-insensitive — so this lines up with the seeded set in step 4
--    where the names happen to coincide, e.g. an old "Rent" item_type maps
--    onto the new "Rent" category instead of creating a duplicate), then
--    point those expense rows at it.
--
--    New/found-but-not-seeded categories default is_opex = false (safe
--    default — doesn't retroactively reclassify old cash-outs as opex).
--    REVIEW these under Settings -> Expense Categories afterward and flip
--    is_opex on for the ones that actually were operating expenses (e.g.
--    if you had an item_type literally named "Rent" or "Salaries" that you
--    were using as the source_type for those expenses).
--
--    Only touches rows where expense_category_id IS NULL, so it's safe to
--    re-run and won't overwrite anything already migrated or already using
--    the new system.
DO $$
DECLARE
  v_user_id uuid := '8a00891a-6617-4806-99b3-3dcc2fbe44ed';
  r RECORD;
  v_category_id bigint;
  v_updated int;
  v_total_updated int := 0;
BEGIN
  FOR r IN
    SELECT DISTINCT it.id AS item_type_id, it.description
    FROM expense e
    JOIN item_type it ON it.id = e.source_type
    WHERE e.user_id = v_user_id
      AND e.expense_category_id IS NULL
      AND e.source_type IS NOT NULL
  LOOP
    SELECT id INTO v_category_id
    FROM expense_category
    WHERE user_id = v_user_id AND lower(name) = lower(r.description);

    IF v_category_id IS NULL THEN
      INSERT INTO expense_category (name, is_opex, user_id)
      VALUES (r.description, false, v_user_id)
      RETURNING id INTO v_category_id;
      RAISE NOTICE 'Created expense_category "%" (id %) migrated from item_type % — review is_opex for it.',
        r.description, v_category_id, r.item_type_id;
    END IF;

    UPDATE expense
    SET expense_category_id = v_category_id
    WHERE user_id = v_user_id
      AND source_type = r.item_type_id
      AND expense_category_id IS NULL;

    GET DIAGNOSTICS v_updated = ROW_COUNT;
    v_total_updated := v_total_updated + v_updated;
  END LOOP;

  RAISE NOTICE 'Backfilled expense_category_id for % expense row(s).', v_total_updated;
END $$;
