-- Recurring operating-expense templates (rent, salaries, etc.) — surfaces
-- on the Dashboard when due, and pre-fills the existing Add Expense flow
-- so the category/amount/schedule don't need to be re-entered from scratch
-- every cycle.
--
-- Purely additive: one new table. Nothing existing is touched.
-- Safe to re-run: every statement is guarded.

CREATE TABLE IF NOT EXISTS recurring_expense (
  id bigint generated by default as identity primary key,
  expense_category_id bigint NOT NULL REFERENCES expense_category(id),
  amount numeric NOT NULL,
  frequency text NOT NULL CHECK (frequency IN ('weekly', 'biweekly', 'monthly')),
  next_due_date date NOT NULL,
  remarks text,
  is_active boolean NOT NULL DEFAULT true,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Same per-user ownership policy as expense_category — included from the
-- start this time. Without this, the table would be either wide open (RLS
-- off) or totally unreadable with no error (RLS on, no policy) depending on
-- the project's defaults, as we found out with expense_category.
ALTER TABLE recurring_expense ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "recurring_expense_select_own" ON recurring_expense;
CREATE POLICY "recurring_expense_select_own" ON recurring_expense
  FOR SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "recurring_expense_insert_own" ON recurring_expense;
CREATE POLICY "recurring_expense_insert_own" ON recurring_expense
  FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "recurring_expense_update_own" ON recurring_expense;
CREATE POLICY "recurring_expense_update_own" ON recurring_expense
  FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "recurring_expense_delete_own" ON recurring_expense;
CREATE POLICY "recurring_expense_delete_own" ON recurring_expense
  FOR DELETE USING (auth.uid() = user_id);
